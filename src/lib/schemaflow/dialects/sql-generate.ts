import type { Column, DefaultValue, Extra, Index, LogicalType, Relation, Schema, SqlDialectId, Table } from '../model/types';
import { constraintName, quote } from './names';

export const INTEGER_KINDS = new Set(['smallint', 'int', 'bigint']);
export const TEMPORAL_KINDS = new Set(['date', 'time', 'timestamp', 'timestamptz']);
export const STRING_KINDS = new Set(['varchar', 'char', 'text']);
export const LOB_KINDS = new Set(['text', 'binary', 'json']);

export const DEFAULT_PRECISION: Record<SqlDialectId, [number, number]> = {
	postgres: [38, 10],
	mysql: [38, 10],
	sqlserver: [38, 10]
};

export function sqlType(dialect: SqlDialectId, type: LogicalType): string {
	switch (type.kind) {
		case 'raw':
			if (type.dialect === dialect) return type.sql;
			return dialect === 'sqlserver' ? 'NVARCHAR(MAX)' : 'TEXT';
		case 'varchar':
			if (dialect === 'postgres') return type.length ? `VARCHAR(${type.length})` : 'VARCHAR';
			if (dialect === 'mysql') return `VARCHAR(${type.length ?? 255})`;
			return (type.length ?? 255) > 4000 ? 'NVARCHAR(MAX)' : `NVARCHAR(${type.length ?? 255})`;
		case 'char':
			if (dialect === 'sqlserver') return `NCHAR(${type.length ?? 1})`;
			return type.length ? `CHAR(${type.length})` : 'CHAR(1)';
		case 'decimal': {
			const name = dialect === 'postgres' ? 'NUMERIC' : 'DECIMAL';
			if (type.precision === undefined) {
				if (dialect === 'postgres') return name;
				const [p, s] = DEFAULT_PRECISION[dialect];
				return `${name}(${p}, ${s})`;
			}
			return type.scale === undefined || type.scale === 0 ? `${name}(${type.precision})` : `${name}(${type.precision}, ${type.scale})`;
		}
		default:
			return SIMPLE[dialect][type.kind];
	}
}


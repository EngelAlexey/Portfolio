import { PGlite } from '@electric-sql/pglite';
import { describe, expect, it } from 'vitest';
import { diffSchemas, isEmptyDiff } from '../model/diff';
import type { Schema } from '../model/types';
import { parseSql } from '../parse/sql-parse';
import { buildMigration, migrate, migrationWarnings, renderMigration, type Warning } from './migrate';
import { generateSql } from './sql-generate';

const parse = (sql: string): Schema => parseSql('postgres', sql).schema;
const render = (m: ReturnType<typeof migrate>, transaction = false) => renderMigration(m, { transaction, describe: (w: Warning) => w.code });

async function catalog(db: PGlite): Promise<string[]> {
	const columns = await db.query<Record<string, unknown>>(
		`SELECT table_name, column_name, data_type, character_maximum_length, numeric_precision, numeric_scale, is_nullable, column_default, is_identity, identity_generation
		 FROM information_schema.columns WHERE table_schema = 'public' ORDER BY table_name, column_name`
	);
	const constraints = await db.query<Record<string, unknown>>(
		`SELECT c.relname AS t, con.contype AS k, pg_get_constraintdef(con.oid) AS def
		 FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid WHERE c.relnamespace = 'public'::regnamespace`
	);
	const indexes = await db.query<Record<string, unknown>>(
		`SELECT tablename AS t, regexp_replace(indexdef, 'INDEX \\S+ ON', 'INDEX ON') AS def FROM pg_indexes
		 WHERE schemaname = 'public' AND indexname NOT IN (SELECT conname FROM pg_constraint)`
	);
	const comments = await db.query<Record<string, unknown>>(
		`SELECT c.relname AS t, a.attname AS col, d.description AS text
		 FROM pg_description d JOIN pg_class c ON c.oid = d.objoid AND c.relnamespace = 'public'::regnamespace
		 LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.objsubid AND d.objsubid > 0 WHERE c.relkind = 'r'`
	);
	const lines = [
		...columns.rows.map((r) => `col ${JSON.stringify(r)}`),
		...constraints.rows.map((r) => `con ${r.t} ${r.k} ${r.def}`),
		...indexes.rows.map((r) => `idx ${r.t} ${r.def}`),
		...comments.rows.map((r) => `cmt ${r.t} ${r.col ?? ''} ${r.text}`)
	];
	return lines.sort();
}

async function run(sql: string): Promise<string[]> {
	const db = new PGlite();
	try {
		await db.exec(sql);
		return await catalog(db);
	} finally {
		await db.close();
	}
}

async function applied(before: Schema, up: string): Promise<string[]> {
	const db = new PGlite();
	try {
		await db.exec(generateSql('postgres', before));
		await db.exec(up);
		return await catalog(db);
	} finally {
		await db.close();
	}
}

const BASE = `
CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(100) NOT NULL UNIQUE, age INTEGER, bio TEXT);
CREATE TABLE posts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, title VARCHAR(200) NOT NULL, views INTEGER DEFAULT 0, price NUMERIC(10, 2), created TIMESTAMP DEFAULT now());
ALTER TABLE posts ADD CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
CREATE INDEX ix_posts_title ON posts (title);
`;


describe('PostgreSQL migrations run on a real engine', () => {
	for (const [name, [beforeSql, afterSql]] of Object.entries(SCENARIOS)) {
		it(name, async () => {
			const before = parse(beforeSql);
			const after = parse(afterSql);
			const up = render(migrate('postgres', before, after), true);
			expect(up.length).toBeGreaterThan(0);
			expect(await applied(before, up)).toEqual(await run(generateSql('postgres', after)));
			const down = render(migrate('postgres', after, before), true);
			expect(await applied(after, down)).toEqual(await run(generateSql('postgres', before)));
		}, 60_000);
	}

	it('renames tables and columns when the design keeps its ids', async () => {
		const before = parse(BASE);
		const after: Schema = JSON.parse(JSON.stringify(before));
		const posts = after.tables.find((t) => t.name === 'posts');
		if (!posts) throw new Error('fixture');
		posts.name = 'articles';
		const title = posts.columns.find((c) => c.name === 'title');
		if (!title) throw new Error('fixture');
		title.name = 'headline';
		const diff = diffSchemas(before, after);
		expect(diff.tablesAdded).toHaveLength(0);
		expect(diff.tablesDropped).toHaveLength(0);
		const up = render(migrate('postgres', before, after), true);
		expect(up).toContain('RENAME TO articles');
		expect(up).toContain('RENAME COLUMN title TO headline');
		expect(await applied(before, up)).toEqual(await run(generateSql('postgres', after)));
	}, 60_000);

	it('keeps rows when a column is renamed', async () => {
		const before = parse('CREATE TABLE t (id INTEGER PRIMARY KEY, name VARCHAR(20));');
		const after: Schema = JSON.parse(JSON.stringify(before));
		const column = after.tables[0]?.columns[1];
		if (!column) throw new Error('fixture');
		column.name = 'label';
		const db = new PGlite();
		try {
			await db.exec(generateSql('postgres', before));
			await db.exec("INSERT INTO t VALUES (1, 'kept');");
			await db.exec(render(migrate('postgres', before, after)));
			expect((await db.query<{ label: string }>('SELECT label FROM t')).rows).toEqual([{ label: 'kept' }]);
		} finally {
			await db.close();
		}
	}, 60_000);

	it('is empty when nothing changed, and reversible in the diff', () => {
		const schema = parse(BASE);
		expect(isEmptyDiff(diffSchemas(schema, parse(BASE)))).toBe(true);
		expect(migrate('postgres', schema, parse(BASE)).steps).toHaveLength(0);
	});
});

describe('migration comments', () => {
	it('keeps a hostile name inside its comment line and its quotes', () => {
		const hostile = 'evil\r\nDROP TABLE users;--\u2028DROP DATABASE prod;';
		const full = parse('CREATE TABLE users (id INT PRIMARY KEY); CREATE TABLE keep (id INT PRIMARY KEY, note TEXT);');
		const named: Schema = JSON.parse(JSON.stringify(full));
		const victim = named.tables[1];
		const note = victim?.columns[1];
		if (!victim || !note) throw new Error('fixture');
		victim.name = hostile;
		note.name = hostile;
		const withoutTable: Schema = { ...named, tables: named.tables.filter((t) => t !== victim), relations: [] };
		const withoutColumn: Schema = JSON.parse(JSON.stringify(named));
		const kept = withoutColumn.tables[1];
		if (!kept) throw new Error('fixture');
		kept.columns = kept.columns.filter((c) => c.name !== hostile);
		const inert = (sql: string) =>
			sql
				.replace(/"(?:[^"]|"")*"/g, '""')
				.replace(/`(?:[^`]|``)*`/g, '``')
				.replace(/\[(?:[^\]]|\]\])*\]/g, '[]')
				.replace(/N?'(?:[^']|'')*'/g, "''");
		for (const dialect of ['postgres', 'mysql', 'sqlserver'] as const) {
			for (const [from, to] of [[named, withoutTable], [named, withoutColumn], [withoutTable, named]] as const) {
				const m = migrate(dialect, from, to);
				const sql = renderMigration(m, { transaction: false, describe: (w: Warning) => `${w.code} ${w.table} ${w.column ?? ''}` });
				const lines = sql.split(/\r\n|\r|\n|\u2028|\u2029/);
				expect(lines.filter((line) => line.startsWith('--')), dialect).toHaveLength(migrationWarnings(m).length);
				const executable = inert(lines.filter((line) => !line.startsWith('--')).join('\n'));
				expect(executable, dialect).not.toMatch(/DROP DATABASE/i);
				expect(executable, dialect).not.toMatch(/DROP TABLE users/i);
				expect(executable, dialect).not.toMatch(/prod/i);
			}
		}
	});

	it('writes one comment line per warning', () => {
		const before = parse(BASE);
		const after = parse('CREATE TABLE users (id BIGINT PRIMARY KEY);');
		const m = migrate('postgres', before, after);
		const comments = render(m).split('\n').filter((line) => line.startsWith('--'));
		expect(comments).toHaveLength(migrationWarnings(m).length);
	});
});

describe('migration warnings', () => {
	const warn = (beforeSql: string, afterSql: string) => migrationWarnings(migrate('postgres', parse(beforeSql), parse(afterSql))).map((w) => `${w.level}:${w.code}`);

	it('marks data loss as dangerous', () => {
		expect(warn(BASE, 'CREATE TABLE users (id BIGINT PRIMARY KEY);')).toEqual(expect.arrayContaining(['danger:drop-table', 'danger:drop-column']));
		expect(warn('CREATE TABLE t (id INT PRIMARY KEY, c VARCHAR(200));', 'CREATE TABLE t (id INT PRIMARY KEY, c VARCHAR(20));')).toContain('danger:type-narrow');
		expect(warn('CREATE TABLE t (id INT PRIMARY KEY, c VARCHAR(20));', 'CREATE TABLE t (id INT PRIMARY KEY, c VARCHAR(200));')).toEqual([]);
	});

	it('marks changes that can fail on existing rows as cautions', () => {
		expect(warn('CREATE TABLE t (id INT PRIMARY KEY, c INT);', 'CREATE TABLE t (id INT PRIMARY KEY, c INT NOT NULL);')).toContain('caution:set-not-null');
		expect(warn('CREATE TABLE t (id INT PRIMARY KEY);', 'CREATE TABLE t (id INT PRIMARY KEY, c INT NOT NULL);')).toContain('caution:add-not-null');
		expect(warn('CREATE TABLE t (id INT PRIMARY KEY, c INT);', 'CREATE TABLE t (id INT PRIMARY KEY, c INT UNIQUE);')).toContain('caution:add-unique');
	});
});

describe('migration syntax for the other engines', () => {
	const before = parse('CREATE TABLE t (id INT PRIMARY KEY, name VARCHAR(20) DEFAULT \'a\', old_col INT, UNIQUE (name));');
	const after: Schema = JSON.parse(JSON.stringify(before));
	const table = after.tables[0];
	if (!table) throw new Error('fixture');
	table.columns = table.columns.filter((c) => c.name !== 'old_col');
	const name = table.columns[1];
	if (!name) throw new Error('fixture');
	name.type = { kind: 'varchar', length: 80 };
	name.default = { kind: 'literal', value: 'b' };
	name.nullable = false;
	table.uniques = [];
	table.columns.push({ id: 'newcol', name: 'created', type: { kind: 'timestamp' }, nullable: false, default: { kind: 'now' } });

	it('uses MODIFY COLUMN and DROP INDEX in MySQL', () => {
		const sql = render(buildMigration('mysql', diffSchemas(before, after)));
		expect(sql).toContain("ALTER TABLE t MODIFY COLUMN name VARCHAR(80) NOT NULL DEFAULT 'b';");
		expect(sql).toContain('ALTER TABLE t DROP INDEX name;');
		expect(sql).toContain('ALTER TABLE t DROP COLUMN old_col;');
		expect(sql).toContain('ALTER TABLE t ADD COLUMN created DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);');
		expect(sql).not.toContain('BEGIN');
	});

	it('drops the default constraint by lookup and separates batches in SQL Server', () => {
		const sql = render(buildMigration('sqlserver', diffSchemas(before, after)), true);
		expect(sql).toContain('sys.default_constraints');
		expect(sql).toContain('ALTER TABLE t ALTER COLUMN name NVARCHAR(80) NOT NULL;');
		expect(sql).toContain("ALTER TABLE t ADD DEFAULT N'b' FOR name;");
		expect(sql).toContain('GO');
		expect(sql.startsWith('SET XACT_ABORT ON;\nBEGIN TRANSACTION;')).toBe(true);
		expect(sql.trimEnd().endsWith('COMMIT;')).toBe(true);
	});

	it('names every declared variable once', () => {
		const sql = render(buildMigration('sqlserver', diffSchemas(before, after)));
		const names = [...sql.matchAll(/DECLARE (@m\d+)/g)].map((m) => m[1]);
		expect(new Set(names).size).toBe(names.length);
	});
});
